#!/usr/bin/env python3
"""Generate src/assets.h (images, fonts, car physics constants) from the
original Unity assets of "Rider Game" (Brackeys)."""
import os, sys
import numpy as np
from PIL import Image, ImageFont, ImageDraw

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ASSETS = os.path.join(ROOT, "assets")
OUT = os.path.join(ROOT, "src", "assets.h")

PPU = 20.0  # screen pixels per world unit (must match game.c)

out = []
def emit(s=""):
    out.append(s)

def rgb565(r, g, b):
    return ((int(r) >> 3) << 11) | ((int(g) >> 2) << 5) | (int(b) >> 3)

def c_array(ctype, name, values, per_line=16, fmt="{}"):
    emit(f"static const {ctype} {name}[{len(values)}] = {{")
    for i in range(0, len(values), per_line):
        emit("  " + ",".join(fmt.format(v) for v in values[i:i + per_line]) + ",")
    emit("};")

def resize_rgba(im, size):
    """Premultiplied-alpha resize, returns float array HxWx4 (0..255)."""
    a = np.asarray(im.convert("RGBA")).astype(np.float32) / 255.0
    pm = a.copy()
    pm[..., :3] *= pm[..., 3:4]
    chans = []
    for c in range(4):
        ch = Image.fromarray(pm[..., c], mode="F").resize(size, Image.LANCZOS)
        chans.append(np.asarray(ch))
    r = np.clip(np.stack(chans, -1), 0, 1)
    alpha = r[..., 3:4]
    rgb = np.where(alpha > 1e-4, r[..., :3] / np.maximum(alpha, 1e-4), 0)
    return np.concatenate([np.clip(rgb, 0, 1), alpha], -1) * 255.0

def sprite(name, im_rgba_f):
    """Emit sprite as rgb565 + 8 bit alpha arrays, cropped to alpha bbox."""
    a = im_rgba_f[..., 3]
    ys, xs = np.nonzero(a > 4)
    y0, y1, x0, x1 = ys.min(), ys.max() + 1, xs.min(), xs.max() + 1
    crop = im_rgba_f[y0:y1, x0:x1]
    h, w = crop.shape[:2]
    col = [rgb565(*crop[y, x, :3]) for y in range(h) for x in range(w)]
    alp = [int(round(crop[y, x, 3])) if crop[y, x, 3] > 4 else 0 for y in range(h) for x in range(w)]
    emit(f"#define {name.upper()}_W {w}")
    emit(f"#define {name.upper()}_H {h}")
    c_array("uint16_t", f"{name}_rgb", col, 16, "0x{:04X}")
    c_array("uint8_t", f"{name}_a", alp, 24)
    return x0, y0, w, h

emit("// Generated by tools/gen_assets.py - do not edit")
emit("#pragma once")
emit("#include <stdint.h>")
emit()

# ---------------------------------------------------------------- background
BG_W, BG_H = 560, 315
BLEND = 90  # cross-fade band that makes the image tile seamlessly
bgsrc = Image.open(os.path.join(ASSETS, "background.png")).convert("RGB").resize((BG_W + BLEND, BG_H), Image.LANCZOS)
a = np.asarray(bgsrc).astype(np.float32)
t = np.linspace(0, 1, BLEND)[None, :, None]
tile = a[:, :BG_W].copy()
tile[:, :BLEND] = a[:, BG_W:BG_W + BLEND] * (1 - t) + a[:, :BLEND] * t
bg = Image.fromarray(np.clip(tile, 0, 255).astype(np.uint8))
q = bg.quantize(colors=256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
pal = q.getpalette()[:256 * 3]
pal += [0] * (256 * 3 - len(pal))
emit(f"#define BG_W {BG_W}")
emit(f"#define BG_H {BG_H}")
c_array("uint16_t", "bg_pal", [rgb565(pal[i * 3], pal[i * 3 + 1], pal[i * 3 + 2]) for i in range(256)], 16, "0x{:04X}")
c_array("uint8_t", "bg_idx", list(q.tobytes()), 40)
emit()

# ---------------------------------------------------------------- car
# Unity: sprite 128px = 1.28 units, Rider transform scale (1.1416092, 2.062011), flipX
CAR_SX, CAR_SY = 1.1416092, 2.062011
CAR_SS = 2  # sprite stored at 2x screen resolution (supersampled rotation)
car = Image.open(os.path.join(ASSETS, "Sportscar-car-icon.png")).transpose(Image.FLIP_LEFT_RIGHT)
cw = int(round(1.28 * CAR_SX * PPU * CAR_SS))
ch = int(round(1.28 * CAR_SY * PPU * CAR_SS))
carf = resize_rgba(car, (cw, ch))
x0, y0, w, h = sprite("car", carf)
# pivot (transform position = image centre) inside the cropped sprite, in sprite pixels
piv_x = cw / 2.0 - x0
piv_y = ch / 2.0 - y0
emit(f"#define CAR_SS {CAR_SS}")
emit(f"#define CAR_PIVOT_X {piv_x:.3f}f")
emit(f"#define CAR_PIVOT_Y {piv_y:.3f}f")

# Collider (PolygonCollider2D path, sprite space), mirrored to match flipX visual
poly = [(0.028535843, -0.1511282), (0.33054206, -0.1541765), (0.4587633, -0.15147477), (0.44492736, -0.057110947),
        (0.48097554, -0.021832585), (0.49843034, 0.0089842975), (0.50356376, 0.04612843), (0.42744, 0.071093164),
        (0.32607865, 0.07832708), (0.14632718, 0.087983854), (-0.051913265, 0.18205029), (-0.25183785, 0.17899019),
        (-0.36372423, 0.12039043), (-0.4108523, 0.091351174), (-0.56865424, 0.074691504), (-0.60590327, -0.057118267),
        (-0.57472575, -0.10803206), (-0.44067612, -0.15571263), (-0.26833445, -0.15637939)]
# (the collider was generated on the flipped sprite, so it already faces right)
poly = [(x * CAR_SX, y * CAR_SY) for x, y in poly]
if sum(poly[i][0] * poly[(i + 1) % len(poly)][1] - poly[(i + 1) % len(poly)][0] * poly[i][1] for i in range(len(poly))) < 0:
    poly = poly[::-1]
A = cx = cy = I = 0.0
n = len(poly)
for i in range(n):
    xa, ya = poly[i]; xb, yb = poly[(i + 1) % n]
    c = xa * yb - xb * ya
    A += c; cx += (xa + xb) * c; cy += (ya + yb) * c
    I += c * (xa * xa + xa * xb + xb * xb + ya * ya + ya * yb + yb * yb)
A /= 2; cx /= 6 * A; cy /= 6 * A; I /= 12
Ic = I - A * (cx * cx + cy * cy)
MASS = 5.0
inertia = MASS * Ic / A
emit(f"#define CAR_MASS {MASS}f")
emit(f"#define CAR_INERTIA {inertia:.5f}f")
emit(f"#define CAR_COM_X {cx:.5f}f  // centre of mass relative to pivot")
emit(f"#define CAR_COM_Y {cy:.5f}f")
# hull sample points (relative to COM), subdivided so spacing <= 0.12
pts = []
for i in range(n):
    xa, ya = poly[i]; xb, yb = poly[(i + 1) % n]
    L = ((xb - xa) ** 2 + (yb - ya) ** 2) ** 0.5
    k = max(1, int(np.ceil(L / 0.12)))
    for j in range(k):
        t = j / k
        pts.append((xa + (xb - xa) * t - cx, ya + (yb - ya) * t - cy))
roof_y = 0.16 * CAR_SY * 0.55 - cy
emit(f"#define CAR_NPTS {len(pts)}")
emit("static const float car_pts[CAR_NPTS][3] = {  // x, y, roof flag")
for x, y in pts:
    emit(f"  {{{x:.4f}f,{y:.4f}f,{1 if y > roof_y else 0}}},")
emit("};")
emit()

# ---------------------------------------------------------------- flag
flag = Image.open(os.path.join(ASSETS, "Sports-Finish-Flag-icon.png"))
fw = int(round(1.28 * 1.3381017 * PPU)); fh = int(round(1.28 * 1.1502686 * PPU))
ff = resize_rgba(flag, (fw, fh))
x0, y0, w, h = sprite("flag", ff)
emit(f"#define FLAG_OX {fw / 2.0 - x0:.2f}f")
emit(f"#define FLAG_OY {fh / 2.0 - y0:.2f}f")
emit()

# ---------------------------------------------------------------- button
btn = Image.open(os.path.join(ASSETS, "Button-Blank-Yellow-icon.png"))
for nm, sz in (("btn_big", 84), ("btn_small", 72)):
    sprite(nm, resize_rgba(btn, (sz, sz)))
emit()

# ---------------------------------------------------------------- menu car (big, tilted like the Unity main menu)
big = car.rotate(-14, resample=Image.BICUBIC, expand=True)
bw = 150
bh = int(round(big.height * bw / big.width * 1.25))
sprite("menucar", resize_rgba(big, (bw, bh)))
emit()

# ---------------------------------------------------------------- DONE! image (alpha mask, 4 bit)
done = np.asarray(Image.open(os.path.join(ASSETS, "done.png")).convert("RGBA")).astype(np.float32)
d = (255 - done[..., :3].mean(-1)) * done[..., 3] / 255.0  # ink = dark AND opaque
dm = Image.fromarray(d.astype(np.uint8)).crop(Image.fromarray(d.astype(np.uint8)).getbbox())
DW = 160
DH = int(round(dm.height * DW / dm.width))
dm = np.asarray(dm.resize((DW, DH), Image.LANCZOS)).astype(np.int32)
vals = np.clip((dm + 8) // 17, 0, 15).flatten().tolist()
if len(vals) % 2: vals.append(0)
packed = [vals[i] | (vals[i + 1] << 4) for i in range(0, len(vals), 2)]
emit(f"#define DONE_W {DW}")
emit(f"#define DONE_H {DH}")
c_array("uint8_t", "done_a4", packed, 32)
emit()

# ---------------------------------------------------------------- fonts (Inter Bold, 4 bit alpha)
FONT = "/usr/share/fonts/opentype/inter/Inter-Bold.otf"
if not os.path.exists(FONT):
    FONT = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
EXTRA = "éèêàçùôîâ"  # mapped to codes 128..
chars = [chr(c) for c in range(32, 127)] + list(EXTRA)
emit(f"#define FONT_NEXTRA {len(EXTRA)}")
emit("static const uint16_t font_extra_cp[FONT_NEXTRA] = {" + ",".join(str(ord(c)) for c in EXTRA) + "};")
for fname, size in (("font_s", 13), ("font_m", 18), ("font_l", 40)):
    font = ImageFont.truetype(FONT, size)
    asc, desc = font.getmetrics()
    H = asc + desc
    offs, widths, data = [], [], []
    for chh in chars:
        adv = int(round(font.getlength(chh)))
        bbox = font.getbbox(chh)
        W = max(adv, bbox[2]) + 1 if chh != " " else adv
        img = Image.new("L", (max(W, 1), H), 0)
        ImageDraw.Draw(img).text((0, 0), chh, font=font, fill=255)
        a = np.asarray(img).astype(np.int32)
        v = np.clip((a + 8) // 17, 0, 15).flatten().tolist()
        if len(v) % 2: v.append(0)
        offs.append(len(data)); widths.append((W, adv))
        data += [v[i] | (v[i + 1] << 4) for i in range(0, len(v), 2)]
    emit(f"#define {fname.upper()}_H {H}")
    emit(f"#define {fname.upper()}_ASC {asc}")
    c_array("uint32_t", f"{fname}_off", offs, 16)
    c_array("uint8_t", f"{fname}_w", [w for w, a in widths], 32)
    c_array("uint8_t", f"{fname}_adv", [a for w, a in widths], 32)
    c_array("uint8_t", f"{fname}_data", data, 40)
    emit()

with open(OUT, "w") as f:
    f.write("\n".join(out) + "\n")
print("wrote", OUT, "car inertia", inertia, "com", cx, cy, "npts", len(pts))
